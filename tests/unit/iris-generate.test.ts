test('settings.glsl: every in-game option, chosen values inside their sorted lists', () => {
  for (const [name, v] of variants()) {
    const files = gen(v);
    const settings = files['shaders/lib/settings.glsl'];
    const opts = parsePackOptions(files);
    assert.deepEqual(opts.problems, [], `${name}: option problems`);
    const s = readSettings(v);
    for (const opt of GAME_OPTIONS) {
      if (opt.kind === 'bool') {
        assert.equal(opts.bools.get(opt.name), opt.value(s), `${name}: ${opt.name}`);
        continue;
      }
      const parsed = opts.values.get(opt.name);
      assert.ok(parsed, `${name}: ${opt.name} declared`);
      const expected = formatValue(opt.value(s), opt.decimals);
      assert.equal(parsed.value, expected, `${name}: ${opt.name} default`);
      assert.ok(parsed.list.includes(expected), `${name}: ${opt.name} list contains the chosen value`);
      const nums = parsed.list.map(Number);
      assert.deepEqual([...nums].sort((a, b) => a - b), nums, `${name}: ${opt.name} list sorted`);
      for (const item of parsed.list) assert.match(item, opt.decimals ? new RegExp(`^-?\\d+\\.\\d{${opt.decimals}}$`) : /^-?\d+$/);
      assert.deepEqual(optionList(opt, s).list, parsed.list);
    }
    assert.equal(opts.bools.size + opts.values.size, GAME_OPTIONS.length, `${name}: no stray options`);
    // Const directives the loaders need are present exactly once.
    for (const c of ['shadowMapResolution', 'shadowDistance', 'sunPathRotation', 'shadowHardwareFiltering', 'shadowDistanceRenderMul']) {
      assert.equal(settings.split(`const `).filter((x) => x.includes(` ${c} =`)).length, 1, `${name}: const ${c}`);
    }
  }
});

