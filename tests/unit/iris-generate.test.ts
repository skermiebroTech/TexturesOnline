test('includes resolve, each lib once per program, no include guards', () => {
  const files = gen(defaults());
  const rel: Files = {};
  for (const [p, c] of Object.entries(files)) if (p.startsWith('shaders/')) rel[p.slice('shaders/'.length)] = c;
  for (const p of Object.keys(rel).filter((x) => /\.(vsh|fsh)$/.test(x))) {
    assert.match(rel[p], /^#version 120\n/, `${p}: #version 120 first`);
    const incs = [...rel[p].matchAll(/#include "([^"]+)"/g)].map((m) => m[1]);
    assert.equal(new Set(incs).size, incs.length, `${p}: a lib included twice`);
    for (const lib of incs) assert.ok(rel[lib.replace(/^\//, '')], `${p}: missing ${lib}`);
    const expanded = expandIncludes(rel, p);
    assert.ok(!/#include/.test(expanded));
    // gl_FragData index is always a literal and every write sits on its own line (OptiFine rewrites line by line).
    for (const line of expanded.split('\n')) {
      if (line.includes('gl_FragData')) assert.match(line.trim(), /^gl_FragData\[\d\] = .+;$/, `${p}: ${line.trim()}`);
    }
    assert.ok(!/\b(iris_\w+|irisMain|moj_import|outColor\d|temp_FragData)/.test(expanded), `${p}: reserved identifier`);
    assert.ok(!/\bgl_FragColor\b/.test(expanded), `${p}: uses gl_FragData only`);
    if (p.endsWith('.fsh') && p !== 'final.fsh') {
      const draw = [...expanded.matchAll(/\/\*\s*DRAWBUFFERS:(\d+)\s*\*\//g)];
      assert.equal(draw.length, 1, `${p}: one DRAWBUFFERS directive`);
      const outputs = new Set([...expanded.matchAll(/gl_FragData\[(\d)\]/g)].map((m) => Number(m[1])));
      assert.equal(Math.max(...outputs) + 1, draw[0][1].length, `${p}: outputs match DRAWBUFFERS`);
    }
  }
  for (const [p, c] of Object.entries(rel)) {
    if (!p.endsWith('.glsl')) continue;
    assert.ok(!/#ifndef\s+\w+\s*\n\s*#define\s+\1/.test(c), `${p}: include guard`);
  }
});

