test('zipIrisPack: shaders/ at the root with directory entries; readable by the app zip reader', async () => {
  const files = gen(presetValues('fantasy'));
  const zip = zipIrisPack(files, { mtime: new Date('2026-01-01T00:00:00Z') });
  const entries = unzipSync(zip);
  const names = Object.keys(entries);
  for (const dir of ['shaders/', 'shaders/lib/', 'shaders/lang/']) {
    assert.ok(names.includes(dir), `directory entry ${dir}`);
    assert.equal(entries[dir].length, 0);
  }
  const fileNames = names.filter((n) => !n.endsWith('/'));
  assert.deepEqual(fileNames.sort(), Object.keys(files).sort());
  for (const n of fileNames) assert.equal(strFromU8(entries[n]), files[n], n);
  const tops = new Set(names.map((n) => n.split('/')[0] + (n.includes('/') ? '/' : '')));
  assert.deepEqual([...tops].sort(), ['README.txt', 'shaders/']);
  // Same bytes for the same input and timestamp.
  assert.deepEqual(zipIrisPack(files, { mtime: new Date('2026-01-01T00:00:00Z') }), zip);
  const back = await readZip(zip);
  assert.deepEqual(Object.keys(back).sort(), Object.keys(files).sort());
  // The generic app writer works too (it just has no directory entries).
  const blob = await writeZip(files);
  const plain = unzipSync(new Uint8Array(await blob.arrayBuffer()));
  assert.equal(strFromU8(plain['shaders/final.fsh']), files['shaders/final.fsh']);
  assert.throws(() => zipIrisPack({ 'a/b': 'x', 'a/b/c': 'y' }));
});

test('deterministic output, safe metadata and file names', () => {
  assert.deepEqual(gen(presetValues('golden')), gen(presetValues('golden')));
  const empty = gen(defaults(), { name: '   ', description: '' });
  assert.ok(empty['shaders/lang/en_US.lang'].includes('option.PACK_INFO=TexturesOnline Shaders\n'));
  assert.ok(empty['shaders/lang/en_US.lang'].includes('option.PACK_INFO.comment=Made with TexturesOnline.\n'));
  const weird = gen(defaults(), { name: '#!  Evil=Name\\with%stuff', description: '*/ /* end' });
  assert.ok(weird['shaders/lang/en_US.lang'].includes('option.PACK_INFO=Evil=Namewithstuff\n'));
  for (const p of shaderFiles(weird)) {
    if (/\.(glsl|vsh|fsh|properties)$/.test(p) && weird[p].includes('Evil')) {
      const line = weird[p].split('\n').find((l) => l.includes('Evil'))!;
      assert.match(line, /^(\/\/|#) [ -~]*$/, `${p}: the name only appears in a plain comment line`);
      assert.ok(!/[\\*%]/.test(line), `${p}: no backslash, * or % in the comment`);
    }
  }
  const long = gen(defaults(), { name: 'x'.repeat(500), description: 'y'.repeat(5000) });
  assert.ok(long['shaders/lang/en_US.lang'].includes(`option.PACK_INFO=${'x'.repeat(64)}\n`));
  assert.equal(irisPackFileName('My Shaders'), 'My Shaders.zip');
  assert.equal(irisPackFileName('a/b:c*?'), 'a_b_c_.zip');
  assert.equal(irisPackFileName(''), 'TexturesOnline Shaders.zip');
  assert.equal(irisPackFileName('pack.zip'), 'pack.zip');
  // Invalid input never breaks generation.
  const garbage = gen({ sunStrength: 'abc', tonemap: 42, skyColor: null } as unknown as OptionValues);
  assert.deepEqual(parsePackOptions(garbage).problems, []);
});
