const META = { name: 'Test Pack', description: 'A pack for tests.' };
type Files = Record<string, string>;

function gen(v: OptionValues, meta = META): Files {
  const files = generateIrisPack(v, meta);
  for (const [p, c] of Object.entries(files)) assert.equal(typeof c, 'string', `${p} is text`);
  return files as Files;
}

/** Every option combination the tests look at. */
function variants(): Array<[string, OptionValues]> {
  const out: Array<[string, OptionValues]> = [['defaults', defaults()]];
  for (const p of PRESETS) out.push([`preset ${p.id}`, presetValues(p.id)]);
  out.push(['all minimum', allExtreme(false)], ['all maximum', allExtreme(true)]);
  const rand = mulberry32(2024);
  for (let i = 0; i < 12; i++) out.push([`random ${i}`, randomOptions(rand, i % 2 === 0)]);
  return out;
}

