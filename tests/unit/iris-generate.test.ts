test('shaders.properties: screens, sliders and profiles only use real options', () => {
  for (const [name, v] of variants()) {
    const files = gen(v);
    const opts = parsePackOptions(files);
    const text = files['shaders/shaders.properties'];
    assert.deepEqual(lintShadersProperties(text, opts), [], name);
    for (const env of ENVIRONMENTS) {
      const macros: Record<string, string> = { ...env.macros };
      for (const [b, on] of opts.bools) if (on) macros[b] = '';
      assert.doesNotThrow(() => preprocessProperties(text, macros), `${name}: balanced #if in ${env.name}`);
    }
  }
  const files = gen(defaults());
  const text = files['shaders/shaders.properties'];
  const props = new Map(propertyLines(text));
  const opts = parsePackOptions(files);
  // Every option is reachable on exactly one screen.
  const placed = [...props.entries()].filter(([k]) => k === 'screen' || (k.startsWith('screen.') && !k.endsWith('.columns')))
    .flatMap(([, v]) => v.split(/\s+/)).filter((x) => /^[A-Za-z]/.test(x));
  assert.deepEqual([...placed].sort(), GAME_OPTIONS.map((o) => o.name).sort());
  // Sliders: every value option with more than a handful of values.
  const sliders = props.get('sliders')!.split(' ');
  for (const [n, o] of opts.values) {
    if (n === 'PACK_INFO' || n === 'TONEMAP') assert.ok(!sliders.includes(n));
    else assert.ok(sliders.includes(n), `${n} is a slider`);
    void o;
  }
  // Profiles set the same options, and the default web settings match the Medium profile.
  const profileKeys = PROFILES.map((p) => p.items.map((i) => i.replace(/^!/, '').split('=')[0]).sort().join(' '));
  assert.equal(new Set(profileKeys).size, 1);
  const medium = PROFILES.find((p) => p.id === 'MEDIUM')!;
  for (const item of medium.items) {
    if (item.includes('=')) {
      const [n, val] = item.split('=');
      assert.equal(opts.values.get(n)!.value, val, `MEDIUM ${n}`);
    } else {
      assert.equal(opts.bools.get(item.replace(/^!/, '')), !item.startsWith('!'), `MEDIUM ${item}`);
    }
  }
  assert.equal(props.get('program.shadow.enabled'), 'SHADOWS');
  assert.equal(props.get('program.composite1.enabled'), 'BLOOM');
  assert.equal(props.get('oldLighting'), 'false');
  assert.equal(props.get('underwaterOverlay'), 'false');
});

