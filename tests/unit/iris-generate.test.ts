/** IDs the GLSL compares against (const ID_* / BE_* / ENTITY_* / ITEM_* in common.glsl). */
function glslIds(files: Files): { block: Set<number>; entity: Set<number>; item: Set<number> } {
  const common = files['shaders/lib/common.glsl'];
  const block = new Set<number>();
  const entity = new Set<number>();
  const item = new Set<number>();
  for (const m of common.matchAll(/const (?:float|int) (ID_\w+|BE_\w+|ENTITY_\w+|ITEM_\w+)\s*=\s*(\d+)(?:\.0)?;/g)) {
    const id = Number(m[2]);
    if (m[1].startsWith('ENTITY_')) entity.add(id);
    else if (m[1].startsWith('ITEM_')) item.add(id);
    else block.add(id);
  }
  return { block, entity, item };
}

test('block.properties: IDs 10001-10020 consistent with the GLSL for every game version', () => {
  const files = gen(defaults());
  const text = files['shaders/block.properties'];
  const ids = glslIds(files);
  assert.deepEqual([...ids.block].sort(), Object.entries(IRIS_IDS).filter(([k]) => !/^(lightning|item)/.test(k)).map(([, v]) => v).sort());
  for (const line of text.split('\n')) {
    assert.ok(!line.trimEnd().endsWith('\\'), 'no line continuations');
    if (line.startsWith('block.')) assert.ok(!line.includes('%') || line.includes('%minecraft:'), line.slice(0, 40));
  }
  const envs: Array<[string, Record<string, string>, boolean]> = [
    ['iris 26.3', { MC_VERSION: '260300', IS_IRIS: '', IRIS_TAG_SUPPORT: '2' }, true],
    ['iris 1.20.2', { MC_VERSION: '12002', IS_IRIS: '', IRIS_TAG_SUPPORT: '2' }, true],
    ['iris 1.16.5', { MC_VERSION: '11605', IS_IRIS: '' }, true],
    ['optifine 1.21.11', { MC_VERSION: '12111' }, true],
    ['optifine 1.12.2', { MC_VERSION: '11202' }, false],
    ['optifine 1.8.9', { MC_VERSION: '10809' }, false],
  ];
  for (const [env, macros, modern] of envs) {
    const entries = propertiesFor(text, macros);
    const keys = entries.map(([k]) => k);
    assert.equal(new Set(keys).size, keys.length, `${env}: every block.N key once`);
    const found = new Set<number>();
    const seenBlocks = new Map<string, number>();
    for (const [key, value] of entries) {
      const m = /^block\.(\d+)$/.exec(key);
      assert.ok(m, `${env}: unexpected key ${key}`);
      const id = Number(m[1]);
      assert.ok(id >= 10001 && id <= 10020, `${env}: ID ${id} in 10001-10020`);
      assert.ok(ids.block.has(id), `${env}: ID ${id} is used by the GLSL`);
      found.add(id);
      const names = value.split(/\s+/);
      assert.ok(names.length > 0 && names.every((n) => /^%?minecraft:[a-z0-9_]+(:[a-z_]+=[a-z0-9_,]+)*$/.test(n)), `${env}: block.${id} syntax`);
      for (const n of names) {
        const plain = n.replace(/^%/, '');
        assert.ok(!seenBlocks.has(plain) || seenBlocks.get(plain) === id, `${env}: ${plain} under two IDs`);
        seenBlocks.set(plain, id);
      }
      if (!modern) assert.ok(!names.some((n) => n.startsWith('%')), `${env}: no tags on legacy versions`);
    }
    assert.deepEqual([...found].sort(), [...ids.block].sort(), `${env}: every GLSL ID is mapped`);
    const leaves = entries.find(([k]) => k === 'block.10001')![1];
    const plants = entries.find(([k]) => k === 'block.10002')![1];
    if (modern) {
      assert.ok(leaves.includes('minecraft:oak_leaves'));
      assert.equal(leaves.includes('%minecraft:leaves'), 'IRIS_TAG_SUPPORT' in macros, `${env}: tags only with IRIS_TAG_SUPPORT`);
      const v = Number(macros.MC_VERSION);
      assert.equal(plants.includes('minecraft:short_grass'), v >= 12003, `${env}: short_grass`);
      assert.equal(/minecraft:grass( |$)/.test(plants), v < 12003, `${env}: grass`);
    } else {
      assert.ok(leaves.includes('minecraft:leaves2'));
      assert.ok(plants.includes('minecraft:tallgrass'));
    }
  }
});

