type PixelName = keyof typeof PIXELARTICONS;
type CustomName = keyof typeof CUSTOM;
type AliasName = keyof typeof ALIASES;
export type IconName = PixelName | CustomName | AliasName;

export const ICON_NAMES = [
  ...Object.keys(PIXELARTICONS),
  ...Object.keys(CUSTOM),
  ...Object.keys(ALIASES),
] as IconName[];

function bitmapToPath(rows: readonly string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === '#') end++;
      d += `M${x * 2} ${y * 2}h${(end - x) * 2}v2h-${(end - x) * 2}z`;
      x = end;
    }
  });
  return d;
}

const templates = new Map<string, SVGSVGElement>();

function template(name: IconName): SVGSVGElement {
  const cached = templates.get(name);
  if (cached) return cached;
  const real = (ALIASES as Record<string, string>)[name] ?? name;
  let markup: string | undefined = (PIXELARTICONS as Record<string, string>)[real];
  if (!markup) {
    const bmp = (CUSTOM as Record<string, readonly string[]>)[real];
    markup = bmp
      ? `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor"><path d="${bitmapToPath(bmp)}"/></svg>`
      : '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor"><path d="M4 4h16v16H4z" opacity=".3"/></svg>';
  }
  const holder = document.createElement('div');
  holder.innerHTML = markup.trim();
  const svg = holder.querySelector('svg') as SVGSVGElement;
  svg.removeAttribute('width');
  svg.removeAttribute('height');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('shape-rendering', 'crispEdges');
  templates.set(name, svg);
  return svg;
}

/**
 * Inline SVG icon inside a span.icon. Icons are drawn on a 24px grid: sizes 24 and 48 are
 * perfectly crisp. Pass `label` for a meaningful standalone icon; otherwise it is decorative.
 */
export function icon(name: IconName, opts: { size?: number; class?: string; label?: string } = {}): HTMLSpanElement {
  const span = document.createElement('span');
  span.className = opts.class ? `icon ${opts.class}` : 'icon';
  const size = opts.size ?? 24;
  if (size !== 24) span.style.setProperty('--icon-size', `${size}px`);
  span.dataset.icon = name;
  if (opts.label) {
    span.setAttribute('role', 'img');
    span.setAttribute('aria-label', opts.label);
  } else {
    span.setAttribute('aria-hidden', 'true');
  }
  span.appendChild(template(name).cloneNode(true));
  return span;
}

/** Replace the glyph of an existing icon span in place. */
export function setIcon(span: HTMLElement, name: IconName): void {
  if (span.dataset.icon === name) return;
  span.dataset.icon = name;
  span.replaceChildren(template(name).cloneNode(true));
}
