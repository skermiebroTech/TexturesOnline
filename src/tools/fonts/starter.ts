/** Parses one ART entry into an 8 × S-wide box at glyph size 8 (cell rows 3-10). */
function parseArt(spec: string): Mask {
  const out = emptyMask(8);
  const m = /^(\d):/.exec(spec);
  const start = m ? Number(m[1]) : 0;
  const rows = (m ? spec.slice(2) : spec).split('/');
  rows.forEach((row, i) => {
    const y = TOP_EXTRA + start + i;
    for (let x = 0; x < row.length && x < 8; x++) if (row[x] === '#' && y < cellH(8)) out[y * 8 + x] = 1;
  });
  return out;
}

function orInto(dst: Mask, src: string[], x0: number, y0: number): void {
  src.forEach((row, i) => {
    const y = y0 + i;
    if (y < 0 || y >= cellH(8)) return;
    for (let x = 0; x < row.length; x++) {
      const xx = x0 + x;
      if (row[x] === '#' && xx >= 0 && xx < 8) dst[y * 8 + xx] = 1;
    }
  });
}

const DOTLESS: Record<string, string> = { i: 'ı', j: 'ȷ', і: 'ı', ј: 'ȷ' };

/** Classic glyph of a character at size 8, or null when there is none. */
function classicGlyph(ch: string, depth = 0): Mask | null {
  if (depth > 3) return null;
  const art = ART[ch];
  if (art) return parseArt(art);
  const same = SAME_AS[ch];
  if (same && same !== ch) return classicGlyph(same, depth + 1);
  const parts = [...ch.normalize('NFD')];
  if (parts.length < 2) return null;
  let base = parts[0];
  const marks = parts.slice(1).map((p) => p.codePointAt(0)!);
  if (!marks.every((m) => MARKS[m])) return null;
  if (marks.some((m) => !MARKS[m].below) && DOTLESS[base]) base = DOTLESS[base];
  const g = classicGlyph(base, depth + 1);
  if (!g) return null;
  // A mark wider than a narrow letter (ï, î) moves the letter under its middle.
  const widest = Math.max(0, ...marks.filter((m) => !MARKS[m].below).map((m) => Math.max(...MARKS[m].rows.map((r) => r.length))));
  const ink = inkWidth(g, 8, cellH(8));
  const shift = widest > ink ? Math.floor((widest - ink) / 2) : 0;
  const out = shift ? shiftMask(g, 8, shift, 0) : g.slice();
  const w = ink + 2 * shift;
  const rows = inkRows(g, 8, cellH(8));
  if (!rows) return null;
  let above = rows[0];
  let below = rows[1];
  for (const m of marks) {
    const mark = MARKS[m];
    const mw = Math.max(...mark.rows.map((r) => r.length));
    if (m === 0x30c && CARON_SIDE.has(base)) {
      orInto(out, ['#', '#'], w + 1, TOP_EXTRA);
      continue;
    }
    if (mark.below) {
      const x = mark.right ? Math.max(0, w - mw) : Math.max(0, Math.floor((w - mw) / 2));
      orInto(out, mark.rows, x, below + 1);
      below += mark.rows.length;
      continue;
    }
    // Only the mark's inked rows count; capitals, tall letters and one-row marks keep a gap row.
    const inked = mark.rows.filter((r) => r.includes('#'));
    const gap = above <= TOP_EXTRA || inked.length === 1 ? 1 : 0;
    const y = above - gap - inked.length;
    orInto(out, inked, Math.max(0, Math.floor((w - mw) / 2)), y);
    above = Math.max(0, y);
  }
  return out;
}

function boldOf(m: Mask, size: GlyphSize): Mask {
  const w = cellW(size);
  const k = size / 8;
  const out = m.slice();
  for (let i = 0; i < m.length; i++) {
    if (!m[i]) continue;
    const x = i % w;
    for (let d = 1; d <= k && x + d < w; d++) out[i + d] = 1;
  }
  return out;
}

function italicOf(m: Mask, size: GlyphSize): Mask {
  const w = cellW(size);
  const h = cellH(size);
  const k = size / 8;
  const out = emptyMask(size);
  for (let y = 0; y < h; y++) {
    // rows above the x-height lean one pixel right, rows below the baseline one pixel left
    const gy = Math.floor(y / k);
    const dx = gy < TOP_EXTRA + 2 ? k : gy >= TOP_EXTRA + 7 ? -k : 0;
    for (let x = 0; x < w; x++) {
      if (!m[y * w + x]) continue;
      const nx = Math.max(0, Math.min(w - 1, x + dx));
      out[y * w + nx] = 1;
    }
  }
  return out;
}

/** Characters the starter style has a glyph for. */
export function starterChars(): number[] {
  return STARTER_CHARS;
}

/** The starter glyph of a character at a glyph size (null when the style has none). */
export function starterGlyph(cp: number, style: StarterStyle, size: GlyphSize): Mask | null {
  const base = classicMask(cp);
  if (!base) return null;
  let m = resizeMask(base, 8, size);
  if (style === 'bold') m = boldOf(m, size);
  else if (style === 'italic') m = italicOf(m, size);
  return isEmptyMask(m) ? null : m;
}

const classicCache = new Map<number, Mask | null>();
function classicMask(cp: number): Mask | null {
  let m = classicCache.get(cp);
  if (m === undefined) {
    m = classicGlyph(String.fromCodePoint(cp));
    classicCache.set(cp, m);
  }
  return m;
}

/** Every character to try: the editor's groups plus anything else drawn above. */
function candidates(): number[] {
  const set = new Set<number>();
  for (let cp = 0x21; cp <= 0x17f; cp++) set.add(cp);
  for (let cp = 0x400; cp <= 0x45f; cp++) set.add(cp);
  for (const s of [...Object.keys(ART), ...Object.keys(SAME_AS)]) set.add(s.codePointAt(0)!);
  [0x218, 0x219, 0x21a, 0x21b, 0x490, 0x491, 0x1e9e].forEach((c) => set.add(c));
  return [...set].sort((a, b) => a - b);
}

const STARTER_CHARS = candidates().filter((cp) => !!classicMask(cp));

/** A whole starter font. */
export function starterFont(style: StarterStyle, size: GlyphSize = 8): FontDoc {
  const doc = newFont(size);
  for (const cp of STARTER_CHARS) setGlyph(doc, cp, starterGlyph(cp, style, size));
  return doc;
}
